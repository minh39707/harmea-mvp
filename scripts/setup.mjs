import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { randomBytes } from 'node:crypto';

if (!existsSync('package.json') || !existsSync('database/001_init.sql'))
  throw new Error('Run in harmea-mvp root');

if (existsSync('.env')) {
  const existing = await readFile('.env', 'utf8');
  const configured = existing.match(/^LOOKUP_SECRET=(.*)$/m)?.[1]?.trim();
  if (
    configured &&
    configured !== 'REPLACE_WITH_GENERATED_VALUE' &&
    Buffer.byteLength(configured) < 32
  )
    throw new Error(
      'Existing LOOKUP_SECRET is shorter than 32 bytes; it was not replaced because stored order hashes may depend on it.'
    );
  const secret =
    configured &&
    configured !== 'REPLACE_WITH_GENERATED_VALUE' &&
    Buffer.byteLength(configured) >= 32
      ? configured
      : randomBytes(32).toString('base64url');
  const updated = /^LOOKUP_SECRET=.*$/m.test(existing)
    ? existing.replace(/^LOOKUP_SECRET=.*$/m, `LOOKUP_SECRET=${secret}`)
    : `${existing.trimEnd()}\nLOOKUP_SECRET=${secret}\n`;
  const migrated = updated
    .replace(/^HOST=127\.0\.0\.1\r?\n/gm, '')
    .replace(/^PORT=4000\r?$/gm, 'PORT=3000')
    .replace(/^APP_URL=http:\/\/localhost:4000\r?$/gm, 'APP_URL=http://localhost:5173');
  if (migrated !== existing) await writeFile('.env', migrated, { mode: 0o600 });
  console.log(
    '.env already exists; preserved database settings and ensured LOOKUP_SECRET is configured.'
  );
} else {
  const mysqlPassword = randomBytes(24).toString('base64url');
  const mysqlRootPassword = randomBytes(24).toString('base64url');
  const lookupSecret = randomBytes(32).toString('base64url');
  let env = (await readFile('.env.example', 'utf8')).replace(/\r\n/g, '\n');
  env = env
    .replace(
      '# Production/container environment template. Copy to a private .env and replace CHANGE_ME values.',
      '# Local development environment generated by npm run setup.'
    )
    .replace(
      '# Required: application database connection. In Compose, use host "db".',
      '# Required: local application database connection.'
    )
    .replace(
      '# Required by the MySQL service in docker-compose.yml. Keep both passwords private.',
      '# Required by the development MySQL service in compose.dev.yaml. Keep passwords private.'
    )
    .replace('NODE_ENV=production', 'NODE_ENV=')
    .replace(
      'DATABASE_URL=mysql://harmea:CHANGE_ME@db:3306/harmea',
      `DATABASE_URL=mysql://harmea:${mysqlPassword}@127.0.0.1:3306/harmea`
    )
    .replace(
      '# TEST_DATABASE_URL=mysql://root:CHANGE_ME@127.0.0.1:3306/mysql',
      `TEST_DATABASE_URL=mysql://root:${mysqlRootPassword}@127.0.0.1:3306/mysql`
    )
    .replace('MYSQL_PASSWORD=CHANGE_ME', `MYSQL_PASSWORD=${mysqlPassword}`)
    .replace('MYSQL_ROOT_PASSWORD=CHANGE_ME', `MYSQL_ROOT_PASSWORD=${mysqlRootPassword}`)
    .replace('LOOKUP_SECRET=CHANGE_ME', `LOOKUP_SECRET=${lookupSecret}`)
    .replace('APP_URL=https://harmea.introd.xyz', 'APP_URL=http://localhost:5173')
    .replace('UPLOAD_DIR=/app/storage/uploads', 'UPLOAD_DIR=./storage/uploads')
    .replace('\n# MYSQL_PORT=3306', '\nMYSQL_PORT=3306');
  await writeFile('.env', env, { flag: 'wx', mode: 0o600 });
  console.log('Created .env. Keep it private; it does not belong in Git or the handoff ZIP.');
}

await mkdir('storage/uploads', { recursive: true });
console.log(
  'Next: start MySQL, run npm run db:migrate, and if migration 005 is deferred, run npm run db:backfill-lookup then npm run db:migrate again.'
);
